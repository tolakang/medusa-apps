// Builds src/lib/data/kh-locations.ts from the official Cambodian postal code
// lists (Ministry of Posts and Telecommunications, Prakas No. 77, 30.12.2025),
// published by Open Development Cambodia under CC BY-SA 4.0:
// https://data.opendevelopmentcambodia.net/en/dataset/postal-codes
//
// Usage: node scripts/build-kh-locations.mjs <province.csv> <district.csv>
// (the English "postal-code_2026_province.csv" and "postal_district_2026.csv").
import { readFileSync, writeFileSync } from "node:fs"

// Codes left out on purpose (TASKS F-028): S'ang repeats Kandal Stueng's
// 080100 and the three Kandal municipalities don't follow the numbering.
// The customer types these postal codes by hand.
const DOUBTFUL_POSTAL = new Set(["810", "811", "812", "813"])

// Other names customers commonly type (matching only; the official name is saved).
const PROVINCE_ALIASES = {
  18: ["Sihanoukville", "Kampong Som"],
  25: ["Tbong Khmum"],
  17: ["Siem Reap"],
}

function parseCsv(path) {
  const text = readFileSync(path, "utf8").replace(/^﻿/, "")
  const rows = []
  let row = [], field = "", quoted = false
  for (let i = 0; i < text.length; i++) {
    const c = text[i]
    if (quoted) {
      if (c === '"' && text[i + 1] === '"') { field += '"'; i++ }
      else if (c === '"') quoted = false
      else field += c
    } else if (c === '"') quoted = true
    else if (c === ",") { row.push(field); field = "" }
    else if (c === "\n" || c === "\r") {
      if (c === "\r" && text[i + 1] === "\n") i++
      row.push(field); rows.push(row); row = []; field = ""
    } else field += c
  }
  if (field || row.length) { row.push(field); rows.push(row) }
  const [head, ...body] = rows
  return body
    .map((r) => Object.fromEntries(head.map((h, i) => [h.trim(), (r[i] ?? "").trim()])))
    .filter((r) => r.pcode)
}

const clean = (s) => s.replace(/​/g, "").replace(/\s+/g, " ").trim()
const [provinceCsv, districtCsv] = process.argv.slice(2)
const provinces = parseCsv(provinceCsv)
const districts = parseCsv(districtCsv)

const data = provinces.map((p) => ({
  name: clean(p.province).replace(/ (Province|Capital)$/, ""),
  name_km: clean(p.province_k),
  aliases: PROVINCE_ALIASES[p.pcode] ?? [],
  districts: districts
    .filter((d) => d.pcode === p.pcode)
    .map((d) => ({
      name: clean(d.district),
      name_km: clean(d.district_k),
      postal_code: DOUBTFUL_POSTAL.has(d.dcode) ? null : d.postal_code,
    })),
}))

if (data.length !== 25 || data.reduce((n, p) => n + p.districts.length, 0) !== 210) {
  throw new Error("Unexpected row counts: check the CSV files")
}

writeFileSync(
  new URL("../src/lib/data/kh-locations.ts", import.meta.url),
  `// GENERATED by scripts/build-kh-locations.mjs; do not edit by hand.
// Cambodian provinces/capital, khan/srok/krong and their postal codes.
// Source: Ministry of Posts and Telecommunications, Prakas No. 77 (30.12.2025),
// via Open Development Cambodia, CC BY-SA 4.0:
// https://data.opendevelopmentcambodia.net/en/dataset/postal-codes
// Adapted: " Province"/" Capital" dropped from province names, four doubtful
// Kandal postal codes left out (null). This file is shared under CC BY-SA 4.0.

export type KhDistrict = { name: string; name_km: string; postal_code: string | null }
export type KhProvince = { name: string; name_km: string; aliases: string[]; districts: KhDistrict[] }

export const KH_PROVINCES: KhProvince[] = ${JSON.stringify(data, null, 2)}
`
)
